#!/usr/bin/env python3
"""切り替え用の compose override を標準出力へ書く。

使い方: gen-override.py new|old|adopt <docker compose config --format json の保存先>

new: 各サービスのイメージを新コードに固定し、DATABASE_URL を新 DB へ向ける。
     接続先以外 (接続数の上限などのクエリ文字列、viewer と analyzer の専用ロール) は、現行の設定をそのまま引き継ぐ。
old: ロールバック用。イメージだけを控えておいた旧コードに戻し、DATABASE_URL は現行の compose の値のままにする。
adopt: master のイメージ (compose が指す参照) へ載せ替えるための設定。DATABASE_URL だけを新 DB へ向け、
       イメージの固定と watchtower の除外ラベルは付けない (載せ替えた後のコンテナは watchtower の管理に戻る)。
new と old は watchtower の自動更新の対象から外すラベルを付ける。
"""
import json
import os
import sys
import urllib.parse

SERVICES = ["crawler", "relabeler", "storage-guard", "viewer", "blocker", "analyzer"]
IMAGE_KEY = {
    "crawler": "CRAWLER",
    "relabeler": "CRAWLER",
    "storage-guard": "CRAWLER",
    "viewer": "VIEWER",
    "blocker": "BLOCKER",
    "analyzer": "ANALYZER",
}
WATCHTOWER_LABEL = "com.centurylinklabs.watchtower.enable"


def fail(message):
    print(f"gen-override: {message}", file=sys.stderr)
    sys.exit(1)


def env(name):
    value = os.environ.get(name, "")
    if not value:
        fail(f"environment variable {name} is required")
    return value


def rewrite_url(service, url):
    parts = urllib.parse.urlsplit(url)
    old_host = os.environ.get("OLD_DB_SERVICE", "postgres")
    if parts.hostname != old_host:
        fail(f"{service}: DATABASE_URL host is '{parts.hostname}', expected '{old_host}'")
    user = urllib.parse.unquote(parts.username or "")
    password = urllib.parse.unquote(parts.password or "")
    if user == env("APP_DB_ROLE"):
        password = env("NEW_APP_DB_PASSWORD")
    netloc = f"{urllib.parse.quote(user, safe='')}:{urllib.parse.quote(password, safe='')}@{env('NEW_DB_HOST')}:5432"
    return urllib.parse.urlunsplit((parts.scheme, netloc, "/" + env("NEW_DB_NAME"), parts.query, ""))


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("new", "old", "adopt"):
        fail("usage: gen-override.py new|old|adopt <compose-config.json>")
    mode = sys.argv[1]
    with open(sys.argv[2], encoding="utf-8") as f:
        services = json.load(f)["services"]
    prefix = "NEW_IMAGE_" if mode == "new" else "ROLLBACK_IMAGE_"

    out = ["# generated by gen-override.py (" + mode + "); do not edit", "services:"]
    for name in SERVICES:
        if name not in services:
            fail(f"service '{name}' is not defined in the production compose")
        out.append(f"  {name}:")
        if mode == "adopt":
            url = (services[name].get("environment") or {}).get("DATABASE_URL")
            if not url:
                fail(f"{name}: DATABASE_URL is not set in the production compose")
            out.append("    environment:")
            out.append(f"      DATABASE_URL: {json.dumps(rewrite_url(name, url))}")
            continue
        # ロールバックは、サービスごとに現行のイメージが違っても戻せるよう、サービス名ごとに指定する。
        key = IMAGE_KEY[name] if mode == "new" else name.upper().replace("-", "_")
        out.append(f"    image: {json.dumps(env(prefix + key))}")
        out.append("    pull_policy: never")
        out.append("    labels:")
        out.append(f'      {WATCHTOWER_LABEL}: "false"')
        if mode == "new":
            url = (services[name].get("environment") or {}).get("DATABASE_URL")
            if not url:
                fail(f"{name}: DATABASE_URL is not set in the production compose")
            out.append("    environment:")
            out.append(f"      DATABASE_URL: {json.dumps(rewrite_url(name, url))}")
    print("\n".join(out))


main()
